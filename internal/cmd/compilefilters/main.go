package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	"rufix/internal/compiledregexp"
	"rufix/internal/redact"
	"rufix/internal/secretvalues"
)

func main() {
	output := flag.String("output", "", "generated Go source path")
	flag.Parse()
	if *output == "" || flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "compilefilters: specify -output")
		os.Exit(1)
	}
	count, err := generate(*output, secretvalues.Rules())
	if err != nil {
		fmt.Fprintln(os.Stderr, "compilefilters:", err)
		os.Exit(1)
	}
	fmt.Printf("compiled %d regex program(s)\n", count)
}

func generate(output string, rules []redact.RuleData) (int, error) {
	patterns := make(map[string]struct{})
	for _, rule := range rules {
		patterns[rule.Match] = struct{}{}
		if rule.RestoreMatch != "" {
			patterns[rule.RestoreMatch] = struct{}{}
		}
	}
	data, err := source(patterns, "programs")
	if err != nil {
		return 0, err
	}
	fixtures := make(map[string]struct{})
	for _, pattern := range fixturePatterns {
		fixtures[pattern] = struct{}{}
	}
	testData, err := source(fixtures, "fixturePrograms")
	if err != nil {
		return 0, err
	}
	if err := writeAtomic(output, data); err != nil {
		return 0, err
	}
	if err := writeAtomic(filepath.Join(filepath.Dir(output), "fixtures_generated_test.go"), testData); err != nil {
		return 0, err
	}
	return len(patterns), nil
}

func source(patterns map[string]struct{}, target string) ([]byte, error) {
	keys := make([]string, 0, len(patterns))
	for pattern := range patterns {
		keys = append(keys, pattern)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("// Code generated by compilefilters; DO NOT EDIT.\npackage compiledregexp\n")
	if len(keys) > 0 {
		b.WriteString("import \"regexp/syntax\"\n")
	}
	fmt.Fprintf(&b, "func init() { %s = map[string]*Regexp{\n", target)
	for i, pattern := range keys {
		re, err := compiledregexp.Compile(pattern)
		if err != nil {
			return nil, fmt.Errorf("invalid regex at sorted index %d; no output written", i)
		}
		fmt.Fprintf(&b, "%q:", pattern)
		if err := compiledregexp.WriteProgram(&b, re); err != nil {
			return nil, fmt.Errorf("serialize regex at sorted index %d", i)
		}
		b.WriteString(",\n")
	}
	b.WriteString("}}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source")
	}
	return formatted, nil
}

func writeAtomic(path string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(path), ".filters-*.tmp")
	if err != nil {
		return err
	}
	name := file.Name()
	defer os.Remove(name)
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}
